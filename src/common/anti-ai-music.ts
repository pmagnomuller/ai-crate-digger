/**
 * Hard policy: never recommend AI-generated music.
 * Used in prompts, retrieval filters, and evals.
 */

/** Artist / label / title fragments that strongly signal synthetic/AI music. */
export const AI_MUSIC_DENYLIST_PATTERNS: RegExp[] = [
  /\bai[\s-]?generated\b/i,
  /\bai[\s-]?music\b/i,
  /\bgenerated by ai\b/i,
  /\bsuno\b/i,
  /\budio\b/i,
  /\baudio craft ai\b/i,
  /\bstable audio\b/i,
  /\bmusicgen\b/i,
  /\baiva\b/i,
  /\bboomy\b/i,
  /\bsoundraw\b/i,
  /\bloudly ai\b/i,
  /\bmubert\b/i,
  /\b artificial intelligence\b/i,
];

export const ANTI_AI_MUSIC_POLICY =
  'HARD RULE: Never recommend AI-generated, synthetic, or model-composed music (including Suno, Udio, MusicGen, and similar). Only recommend human-made music. If a candidate appears AI-generated, skip it and pick another human release.';

export function looksLikeAiGeneratedMusic(input: {
  title?: string;
  artist?: string;
  label?: string;
  notes?: string;
  isAiGenerated?: boolean;
}): boolean {
  if (input.isAiGenerated === true) return true;
  const haystack = [input.title, input.artist, input.label, input.notes]
    .filter((v): v is string => typeof v === 'string' && v.length > 0)
    .join(' | ');
  if (!haystack) return false;
  return AI_MUSIC_DENYLIST_PATTERNS.some((re) => re.test(haystack));
}

/** Mongo `$match` fragment excluding catalog rows flagged as AI-generated. */
export function antiAiCatalogMatch(): Record<string, unknown> {
  return {
    $and: [
      { isAiGenerated: { $ne: true } },
      {
        title: {
          $not: /(ai[\s-]?generated|suno|udio|musicgen)/i,
        },
      },
      {
        artist: {
          $not: /(ai[\s-]?generated|suno|udio|musicgen)/i,
        },
      },
    ],
  };
}
